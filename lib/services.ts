export function getServicePage(slug: string): ServicePage | undefined {
  return servicePages.find((s) => s.slug === slug);
}

export function hasServicePages(locale: Locale): boolean {
  return serviceLocales.includes(locale);
}

/** Homepage label → service page slug (only for locales with service pages). */
export function serviceSlugForLabel(locale: Locale, label: string): string | undefined {
  if (!hasServicePages(locale)) return undefined;
  return servicePages.find((s) => s.homeLabel === label)?.slug;
}
